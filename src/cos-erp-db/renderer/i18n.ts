let language: DatabaseLanguage = 'en';
try {
  if (window.localStorage.getItem(STORAGE_KEY) === 'vi') language = 'vi';
} catch {
  // localStorage can be unavailable in a restricted renderer. The in-memory switch still works.
}

export function databaseLanguage(): DatabaseLanguage {
  return language;
}

export function setDatabaseLanguage(next: DatabaseLanguage): void {
  if (language === next) return;
  language = next;
  try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* Keep the current window usable. */ }
  // Database renderer nodes use the upstream `ui()` binding helper with callbacks that call
  // this module's `t()`. Re-applying the unchanged app language asks those live callbacks to
  // repaint without changing the language of the rest of Chat On Steroids.
  refreshUpstreamBindings(currentLanguage());
  window.dispatchEvent(new window.CustomEvent('cos:database-language-changed', { detail: { language: next } }));
}

export function t(source: string, args: readonly unknown[] = []): string {
  const translated = language === 'vi' ? (vi[source] ?? source) : source;
  return translated.replace(/\{(\d+)\}/g, (match, index: string) =>
    Number(index) < args.length ? String(args[Number(index)]) : match
  );
}
